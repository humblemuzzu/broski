#!/usr/bin/env bash
# Generates the vendored @pierre/highlights C source and Rust lookup tables in
# packages/link/render/ from a pinned npm release using WABT's wasm2c.
#
# Usage: scripts/generate-highlights.sh
# Needs curl, tar (with xz), bun (to read the package's ESM tables) and macOS arm64.
# Downloads are cached under BROSKI_CACHE (~/.cache/broski) and verified by SHA-256.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
RENDER="$ROOT/packages/link/render"
VENDOR="$RENDER/vendor/highlights"
GENERATED_RS="$RENDER/src/highlight/generated.rs"
CACHE="${BROSKI_CACHE:-$HOME/.cache/broski}"

HIGHLIGHTS_VERSION=0.5.1
HIGHLIGHTS_SHA256=bfe36cc1c5ef09030d4db599a5a1b4db81c68dc47c098e2ab78bedad657d282b

WABT_VERSION=1.0.42
WABT_SHA256=3f654779b436c628db3ca4323c51538815f5fbc887a6d5f3bb1c18d36281e240

SIMDE_VERSION=0.8.2
SIMDE_SHA256=59068edc3420e75c5ff85ecfd80a77196fb3a151227a666cc20abb313a5360bf

if [[ "$(uname -sm)" != "Darwin arm64" ]]; then
  echo "error: scripts/generate-highlights.sh pins wabt $WABT_VERSION for Darwin arm64 (got $(uname -sm))" >&2
  exit 1
fi

sha256() {
  shasum -a 256 "$1" | cut -d' ' -f1
}

fetch() {
  local url=$1 file="$CACHE/downloads/$2" sum=$3
  if [[ ! -f $file ]]; then
    mkdir -p "$CACHE/downloads"
    curl --fail --location --silent --show-error --output "$file.part" "$url"
    mv "$file.part" "$file"
  fi
  if [[ "$(sha256 "$file")" != "$sum" ]]; then
    echo "error: $file does not match pinned SHA-256 $sum; delete it to download again" >&2
    exit 1
  fi
}

unpack() {
  if [[ ! -d "$CACHE/$2" ]]; then
    mkdir -p "$CACHE/$2.part"
    tar -xf "$CACHE/downloads/$1" -C "$CACHE/$2.part" --strip-components 1
    mv "$CACHE/$2.part" "$CACHE/$2"
  fi
}

fetch "https://registry.npmjs.org/@pierre/highlights/-/highlights-$HIGHLIGHTS_VERSION.tgz" \
  "pierre-highlights-$HIGHLIGHTS_VERSION.tgz" "$HIGHLIGHTS_SHA256"
fetch "https://github.com/WebAssembly/wabt/releases/download/$WABT_VERSION/wabt-$WABT_VERSION-macos-arm64.tar.gz" \
  "wabt-$WABT_VERSION-macos-arm64.tar.gz" "$WABT_SHA256"
fetch "https://github.com/simd-everywhere/simde/releases/download/v$SIMDE_VERSION/simde-amalgamated-$SIMDE_VERSION.tar.xz" \
  "simde-amalgamated-$SIMDE_VERSION.tar.xz" "$SIMDE_SHA256"

unpack "pierre-highlights-$HIGHLIGHTS_VERSION.tgz" "pierre-highlights-$HIGHLIGHTS_VERSION"
unpack "wabt-$WABT_VERSION-macos-arm64.tar.gz" "wabt-$WABT_VERSION"
unpack "simde-amalgamated-$SIMDE_VERSION.tar.xz" "simde-amalgamated-$SIMDE_VERSION"

PKG="$CACHE/pierre-highlights-$HIGHLIGHTS_VERSION"
WABT="$CACHE/wabt-$WABT_VERSION"
SIMDE="$CACHE/simde-amalgamated-$SIMDE_VERSION"
WASM="$PKG/dist/highlights.wasm"
WASM_SHA256="$(sha256 "$WASM")"
BANNER="Generated by scripts/generate-highlights.sh from @pierre/highlights $HIGHLIGHTS_VERSION (highlights.wasm sha256 $WASM_SHA256) with wabt $WABT_VERSION. Do not edit."

echo "==> Running wasm2c $WABT_VERSION on @pierre/highlights $HIGHLIGHTS_VERSION"
SCRATCH="$(mktemp -d)"
trap 'rm -rf "$SCRATCH"' EXIT
"$WABT/bin/wasm2c" "$WASM" -n highlights -o "$SCRATCH/highlights.c"

rm -rf "$VENDOR"
mkdir -p "$VENDOR/wasm2c" "$VENDOR/simde/wasm"

for f in highlights.c highlights.h; do
  {
    echo "/* $BANNER */"
    cat "$SCRATCH/$f"
  } > "$VENDOR/$f"
done

cp "$WABT/include/wasm-rt.h" "$VENDOR/wasm2c/wasm-rt.h"
for f in wasm-rt-impl.h wasm-rt-impl.c wasm-rt-impl-tableops.inc wasm-rt-mem-impl.c wasm-rt-mem-impl-helper.inc; do
  cp "$WABT/share/wabt/wasm2c/$f" "$VENDOR/wasm2c/$f"
done

cp "$SIMDE/wasm/simd128.h" "$VENDOR/simde/wasm/simd128.h"
cp "$PKG/LICENSE.md" "$VENDOR/LICENSE.md"
cp "$PKG/NOTICE.md" "$VENDOR/NOTICE.md"

echo "==> Generating $GENERATED_RS"
PKG_DIR="$PKG" \
  OUT_FILE="$GENERATED_RS" \
  HIGHLIGHTS_VERSION="$HIGHLIGHTS_VERSION" \
  HIGHLIGHTS_WASM_SHA256="$WASM_SHA256" \
  WABT_VERSION="$WABT_VERSION" \
  BANNER="$BANNER" \
  bun -e '
    import { writeFileSync } from "node:fs";
    import { pathToFileURL } from "node:url";

    const pkg = process.env.PKG_DIR;
    const { default: languages } = await import(pathToFileURL(`${pkg}/dist/languages.js`).href);
    const { default: tokenTypes } = await import(pathToFileURL(`${pkg}/dist/token-types.js`).href);

    const entries = Object.entries(languages)
      .map(([name, id]) => [name.toLowerCase(), Number(id)])
      .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

    const maxId = Math.max(...entries.map(([, id]) => id));
    const byId = Array.from({ length: maxId + 1 }, () => []);
    for (const [name, id] of entries) byId[id].push(name);

    // Pick a stable canonical name per language ID: longest key without a hyphen unless
    // all keys have hyphens (or "plain" for 0). Display labels override common languages.
    const canonical = byId.map((names, id) => {
      if (id === 0) return "plain";
      const candidates = names.filter((n) => !n.includes("-"));
      const pool = candidates.length > 0 ? candidates : names;
      return [...pool].sort((a, b) => b.length - a.length || (a < b ? -1 : 1))[0];
    });

    const lines = [
      `// ${process.env.BANNER}`,
      "",
      `#[cfg(test)] pub const HIGHLIGHTS_VERSION: &str = ${JSON.stringify(process.env.HIGHLIGHTS_VERSION)};`,
      `#[cfg(test)] pub const HIGHLIGHTS_WASM_SHA256: &str = ${JSON.stringify(process.env.HIGHLIGHTS_WASM_SHA256)};`,
      `#[cfg(test)] pub const WABT_VERSION: &str = ${JSON.stringify(process.env.WABT_VERSION)};`,
      "",
      "/// Lowercase language names and aliases sorted for binary search, mapped to Pierre Wasm IDs.",
      "pub const LANGUAGES: &[(&str, u8)] = &[",
      ...entries.map(([name, id]) => `    (${JSON.stringify(name)}, ${id}),`),
      "];",
      "",
      "/// Canonical lowercase name indexed by Pierre Wasm language ID.",
      "pub const CANONICAL_LANGUAGES: &[&str] = &[",
      ...canonical.map((name) => `    ${JSON.stringify(name)},`),
      "];",
      "",
      "/// Pierre token type names indexed by Wasm token ID.",
      "pub const TOKEN_TYPES: &[&str] = &[",
      ...tokenTypes.map((name) => `    ${JSON.stringify(name)},`),
      "];",
      "",
    ];
    writeFileSync(process.env.OUT_FILE, lines.join("\n"));
  '

echo "==> Done: $VENDOR and $GENERATED_RS"
